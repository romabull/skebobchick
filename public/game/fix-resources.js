// ============ ⚠️ КОНФЛИКТУЮЩИЕ НАЗВАНИЯ ============
// Некоторые провинции в разных странах имеют одинаковые имена ("Альпы", "Пустыня").
// Для них ресурс задаём по country.
const RESOURCES_BY_COUNTRY = {
    // 'Альпы' во Франции = metal, в Италии = metal, в Австрии = metal — везде metal, ок.
    // 'Пустыня' — только у Ирака (oil) и UK (oil) — ок.
    // Если появятся конфликты — добавим сюда:
    // 'Альпы|france': 'metal',
    // 'Альпы|italy': 'metal',
};

// ============ 🔧 ОСНОВНАЯ ЛОГИКА ============
function main() {
    if (!fs.existsSync(MAP_FILE)) {
        console.error(`❌ Файл не найден: ${MAP_FILE}`);
        process.exit(1);
    }

    let text = fs.readFileSync(MAP_FILE, 'utf8');

    // Сохраним бэкап
    const backup = MAP_FILE + '.backup-' + Date.now();
    fs.writeFileSync(backup, text, 'utf8');
    console.log(`💾 Бэкап: ${path.basename(backup)}`);

    // Регулярка: захватывает блок провинции и внутри него name, country, resource
    // Работает только для "плоских" регионов (city_* и *_main).
    // Для city_4 (Люксембург) — тоже сработает.

    const regionRegex = /(\b\w+\s*:\s*\{\s*[\s\S]*?name\s*:\s*"([^"]+)"[\s\S]*?country\s*:\s*"([^"]+)"[\s\S]*?resource\s*:\s*")([^"]+)(")/g;

    let replaced = 0;
    let skipped = 0;
    const notFound = new Set(Object.keys(RESOURCES));

    text = text.replace(regionRegex, (match, prefix, name, country, oldRes, suffix) => {
        // Воду не трогаем
        if (country === 'water') {
            skipped++;
            return match;
        }

        // Пробуем сначала по country+name, потом просто по name
        let newRes = RESOURCES_BY_COUNTRY[`${name}|${country}`];
        if (!newRes) newRes = RESOURCES[name];

        if (!newRes) {
            // Нет в таблице — оставляем как есть
            skipped++;
            return match;
        }

        notFound.delete(name);
        replaced++;

        const shortName = name.length > 25 ? name.slice(0, 22) + '...' : name;
        console.log(`  ✏️  ${shortName.padEnd(25)} [${country.padEnd(15)}] ${oldRes.padEnd(6)} → ${newRes}`);

        return prefix + newRes + suffix;
    });

    fs.writeFileSync(MAP_FILE, text, 'utf8');

    console.log('\n============================');
    console.log(`✅ Заменено: ${replaced}`);
    console.log(`⏭️  Пропущено (вода/нет в таблице): ${skipped}`);

    if (notFound.size > 0) {
        console.log('\n⚠️  Провинции из таблицы, не найденные в файле:');
        [...notFound].sort().forEach(n => console.log(`   • ${n}`));
    }

    console.log('\n🎉 Готово! Не забудь убрать autoAssignResources(EUROPE_MAP) из game.js');
}

main();